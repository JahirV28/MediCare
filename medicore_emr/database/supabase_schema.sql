-- ============================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Permite lectura y escritura tanto para usuarios anonimos como autenticados
-- (Ajustar segun requerimientos especificos de produccion)
-- ============================================================

DO $$
DECLARE
  tbl text;
BEGIN
  FOR tbl IN
    SELECT tablename FROM pg_tables WHERE schemaname = 'public'
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', tbl);
    EXECUTE format('DROP POLICY IF EXISTS "Allow all for authenticated and anon" ON public.%I;', tbl);
    EXECUTE format('CREATE POLICY "Allow all for authenticated and anon" ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);', tbl);
  END LOOP;
END $$;


